//! Generates the `--list-rules` catalog from the rule manifest (TRD §8.2, §9.6) and records the
//! build identity printed by `--version`: target, commit, and build date.
//!
//! Build scripts receive their inputs through Cargo's environment, so the reads below are the
//! documented exception to the no-environment rule; none of them reaches the runtime binary
//! except as these fixed strings.
#![allow(clippy::disallowed_methods)]

use std::fmt::Write as _;
use std::path::PathBuf;

use spymonk_redact_rules::Detector;

fn main() {
    let manifest = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../rules/rules.v1.json");
    println!("cargo:rerun-if-changed={}", manifest.display());
    println!("cargo:rerun-if-env-changed=SOURCE_COMMIT");
    println!("cargo:rerun-if-env-changed=SOURCE_DATE_EPOCH");

    let bytes = std::fs::read(&manifest).expect("rule manifest is readable");
    let compiled = spymonk_redact_rules::compile(&bytes).expect("rule manifest is valid");

    let mut out = String::from("// @generated by crates/cli/build.rs from rules/rules.v1.json.\n");
    out.push_str("pub static CATALOG: &[CatalogRule] = &[\n");
    for rule in &compiled.rules {
        let formats = if rule.detector == Detector::TokenFormat {
            rule.data
                .formats
                .iter()
                .map(|f| format!("({:?}, {:?})", f.id, f.provider))
                .collect::<Vec<_>>()
                .join(", ")
        } else {
            String::new()
        };
        let _ = writeln!(
            out,
            "    CatalogRule {{ id: {:?}, name: {:?}, family: {:?}, optional: {}, default_enabled: {}, placeholder: {:?}, formats: &[{}] }},",
            rule.id,
            rule.name,
            rule.detector.manifest_name(),
            rule.optional,
            rule.default_enabled,
            rule.placeholder,
            formats
        );
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets OUT_DIR"));
    std::fs::write(out_dir.join("catalog.rs"), out).expect("catalog is writable");

    let target = std::env::var("TARGET").expect("Cargo sets TARGET");
    let commit = std::env::var("SOURCE_COMMIT")
        .ok()
        .map(|c| {
            c.chars()
                .filter(char::is_ascii_hexdigit)
                .take(12)
                .collect::<String>()
        })
        .filter(|c| !c.is_empty())
        .unwrap_or_else(|| "unknown".into());
    let date = std::env::var("SOURCE_DATE_EPOCH")
        .ok()
        .and_then(|s| s.trim().parse::<i64>().ok())
        .map(civil_date)
        .unwrap_or_else(|| "unknown".into());
    println!("cargo:rustc-env=SPYMONK_BUILD_TARGET={target}");
    println!("cargo:rustc-env=SPYMONK_BUILD_COMMIT={commit}");
    println!("cargo:rustc-env=SPYMONK_BUILD_DATE={date}");
}

/// UTC calendar date of a Unix timestamp (H. Hinnant's days-from-civil inverse).
fn civil_date(epoch: i64) -> String {
    let days = epoch.div_euclid(86_400);
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!("{year:04}-{month:02}-{day:02}")
}
