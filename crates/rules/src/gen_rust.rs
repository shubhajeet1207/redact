//! Rust table generation for `spymonk-redact-core` (TRD §8.2).
//!
//! The output references types defined in the core crate's `rules` module (`DetectorKind`,
//! `Charset`, `Segment`, `TokenFormat`) and uses only `core` types, so it compiles under `no_std`.
//! String literals are emitted with `{:?}`, which always yields a valid Rust literal.

use std::fmt::Write as _;

use crate::{Compiled, Detector};

pub fn generate_rust(c: &Compiled) -> String {
    let mut s = String::new();
    let n = c.rules.len();
    let w = &mut s;
    // `fmt::Write` for `String` never fails; results are discarded deliberately.
    let _ = writeln!(
        w,
        "// @generated by spymonk-redact-rules from rules/rules.v1.json. Do not edit."
    );
    let _ = writeln!(w, "pub const SCHEMA_VERSION: u32 = {};", c.schema_version);
    let _ = writeln!(w, "pub const RULES_VERSION: &str = {:?};", c.rule_version);
    let _ = writeln!(w, "pub const RULES_SHA256: &str = {:?};", c.sha256_hex);
    let _ = writeln!(w, "pub const RULE_COUNT: usize = {n};");

    let list = |items: Vec<String>| items.join(", ");
    let _ = writeln!(
        w,
        "pub const RULE_IDS: [&str; RULE_COUNT] = [{}];",
        list(c.rules.iter().map(|r| format!("{:?}", r.id)).collect())
    );
    let _ = writeln!(
        w,
        "pub const RULE_NAMES: [&str; RULE_COUNT] = [{}];",
        list(c.rules.iter().map(|r| format!("{:?}", r.name)).collect())
    );
    let _ = writeln!(
        w,
        "pub const RULE_DETECTOR: [DetectorKind; RULE_COUNT] = [{}];",
        list(
            c.rules
                .iter()
                .map(|r| format!("DetectorKind::{}", r.detector.rust_name()))
                .collect()
        )
    );
    let _ = writeln!(
        w,
        "pub const RULE_DEFAULT: [bool; RULE_COUNT] = [{}];",
        list(
            c.rules
                .iter()
                .map(|r| r.default_enabled.to_string())
                .collect()
        )
    );
    let _ = writeln!(
        w,
        "pub const RULE_OPTIONAL: [bool; RULE_COUNT] = [{}];",
        list(c.rules.iter().map(|r| r.optional.to_string()).collect())
    );
    let _ = writeln!(
        w,
        "pub const RULE_PLACEHOLDER: [&str; RULE_COUNT] = [{}];",
        list(
            c.rules
                .iter()
                .map(|r| format!("{:?}", r.placeholder))
                .collect()
        )
    );
    let ranks: Vec<String> = c
        .rules
        .iter()
        .map(|r| {
            let rank = c.precedence.iter().position(|p| *p == r.id).unwrap_or(n);
            rank.to_string()
        })
        .collect();
    let _ = writeln!(
        w,
        "pub const PRECEDENCE_RANK: [u8; RULE_COUNT] = [{}];",
        list(ranks)
    );
    let _ = writeln!(
        w,
        "pub const PLACEHOLDERS: [&str; {}] = [{}];",
        c.placeholders.len(),
        list(c.placeholders.iter().map(|p| format!("{p:?}")).collect())
    );

    for d in Detector::ALL {
        let idx = c.rules.iter().position(|r| r.detector == d).unwrap_or(n);
        let name = d.manifest_name().replace('-', "_").to_ascii_uppercase();
        let _ = writeln!(w, "pub const IDX_{name}: usize = {idx};");
    }

    let named = &c.rule(Detector::NamedValue).data;
    let _ = writeln!(
        w,
        "pub const SECRET_SINGLE_ALIASES: &[&str] = &[{}];",
        strs(&named.single_aliases)
    );
    let pairs: Vec<String> = named
        .pair_aliases
        .iter()
        .map(|(a, b)| format!("({a:?}, {b:?})"))
        .collect();
    let _ = writeln!(
        w,
        "pub const SECRET_PAIR_ALIASES: &[(&str, &str)] = &[{}];",
        list(pairs)
    );
    let _ = writeln!(
        w,
        "pub const SKIP_VALUES: &[&str] = &[{}];",
        strs(&named.skip_values)
    );

    let auth = &c.rule(Detector::Authorization).data;
    let _ = writeln!(
        w,
        "pub const AUTH_HEADERS: &[&str] = &[{}];",
        strs(&auth.headers)
    );
    let _ = writeln!(
        w,
        "pub const AUTH_SCHEMES: &[&str] = &[{}];",
        strs(&auth.schemes)
    );
    let cookie = &c.rule(Detector::Cookie).data;
    let _ = writeln!(
        w,
        "pub const COOKIE_REQUEST_HEADERS: &[&str] = &[{}];",
        strs(&cookie.request_headers)
    );
    let _ = writeln!(
        w,
        "pub const COOKIE_RESPONSE_HEADERS: &[&str] = &[{}];",
        strs(&cookie.response_headers)
    );

    let home = &c.rule(Detector::HomePath).data;
    let _ = writeln!(
        w,
        "pub const HOME_POSIX_PREFIXES: &[&str] = &[{}];",
        strs(&home.posix_prefixes)
    );
    let _ = writeln!(
        w,
        "pub const HOME_WINDOWS_DIR: &str = {:?};",
        home.windows_directory
    );

    let ip = &c.rule(Detector::PrivateIp).data;
    let v4: Vec<String> = ip
        .ipv4
        .iter()
        .map(|(net, len)| format!("(0x{net:08x}, {len})"))
        .collect();
    let _ = writeln!(w, "pub const IPV4_RANGES: &[(u32, u8)] = &[{}];", list(v4));
    let v6: Vec<String> = ip
        .ipv6
        .iter()
        .map(|(net, len)| format!("(0x{net:032x}, {len})"))
        .collect();
    let _ = writeln!(w, "pub const IPV6_RANGES: &[(u128, u8)] = &[{}];", list(v6));

    let pem = &c.rule(Detector::PemBlock).data;
    let _ = writeln!(
        w,
        "pub const PEM_LABEL_SUFFIXES: &[&str] = &[{}];",
        strs(&pem.label_suffixes)
    );
    let _ = writeln!(
        w,
        "pub const PEM_MAX_LABEL_PREFIX: usize = {};",
        pem.max_label_prefix
    );

    let tok = &c.rule(Detector::TokenFormat).data;
    let _ = writeln!(w, "pub const TOKEN_FORMATS: &[TokenFormat] = &[");
    for f in &tok.formats {
        let segs: Vec<String> = f
            .segments
            .iter()
            .map(|sg| {
                format!(
                    "Segment {{ charset: Charset::{}, min: {}, exact: {} }}",
                    sg.charset.rust_name(),
                    sg.min,
                    sg.exact
                )
            })
            .collect();
        let _ = writeln!(
            w,
            "    TokenFormat {{ id: {:?}, provider: {:?}, prefixes: &[{}], segments: &[{}] }},",
            f.id,
            f.provider,
            strs(&f.prefixes),
            list(segs)
        );
    }
    let _ = writeln!(w, "];");
    s
}

fn strs(items: &[String]) -> String {
    items
        .iter()
        .map(|i| format!("{i:?}"))
        .collect::<Vec<_>>()
        .join(", ")
}
